def safe_segment(text: str, limit: int = 0) -> str:
    """ทำให้ข้อความใช้เป็น "ชื่อโฟลเดอร์/ไฟล์เดียว" ได้อย่างปลอดภัย

    หัวใจคือ **"/" ต้องหายไป** ไม่งั้นกลายเป็นตัวคั่นโฟลเดอร์
    ผู้ใช้ระบุเองว่าอยากได้ "DM และ หรือ HT" ⇒ แทน "/" ด้วยช่องว่าง ไม่ใช่ขีดหรือลบทิ้ง
    เพราะต้องอ่านออกและยังค้นเจอด้วยคำเดิม
    """
    s = re.sub(r"[/\\]+", " ", text or "")
    s = re.sub(r"[\x00-\x1f]+", " ", s)          # อักขระควบคุมทำ metadata พัง
    s = re.sub(r"\s+", " ", s).strip(" .")        # จุดท้ายชื่อทำให้บางระบบมองเป็นนามสกุล
    return s[:limit].strip() if limit else s


def classify(title: str, category: str = "") -> tuple[str, str]:
    """คืน (โฟลเดอร์โดเมน, โฟลเดอร์ย่อย) จากชื่อตัวชี้วัด + ชื่อหมวดของ HDC

    ดูทั้งสองอย่างเพราะบางตัวชี้วัดชื่อไม่บอกโรค แต่หมวดบอก
    (เช่น "CKD 2.7 ... ตรวจ serum K" อยู่หมวด "Service Plan สาขาไต")
    """
    hay = f"{title} {category}".lower()
    for words, domain, sub in _RULES:
        if any(w in hay for w in words):
            return domain, sub
    return OTHER, safe_segment(category, 40) or "ไม่ระบุหมวด"


def build_vault_path(title: str, category: str = "", limit: int = 150,
                     suffix: str = " (HDC)") -> tuple[str, str]:
    """คืน (โฟลเดอร์, ชื่อไฟล์ไม่รวม .csv) ที่ประกอบแล้วยาวไม่เกิน `limit`

    `x-amz-meta-path` ตัดที่ 150 ตัวเงียบ ๆ ถ้าเกินแล้ว folder tree จะพัง
    ไฟล์จะหาไม่เจอจากปุ่ม "ข้อมูลสถิติ" ⇒ ต้องคุมความยาวตั้งแต่ตอนสร้าง
    """
    domain, sub = classify(title, category)
    clean = safe_segment(title)
    folder = f"{domain}/{sub}/{clean}"

    # เผื่อที่ให้ "/" + ".csv" + suffix ของชื่อไฟล์
    def room_for(f: str) -> int:
        return limit - len(f) - 1 - len(".csv") - len(suffix)

    if room_for(folder) < 12:
        folder = f"{domain}/{sub}"              # ตัดชั้นชื่อตัวชี้วัดออกก่อน
    if room_for(folder) < 12:
        folder = domain                          # ยังไม่พอก็เหลือแค่โดเมน
    return folder, clean[: max(room_for(folder), 1)].strip() + suffix
