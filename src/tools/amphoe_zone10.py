# "00" ไม่ใช่รหัสอำเภอตามระบบ มท. — แปลว่าต้นทางไม่ได้ลงรหัสอำเภอให้สถานพยาบาลนั้น
# เจอจริง 1 แถวใน 75,557 (hospcode 77466 จ.ศรีสะเกษ ปี 2568) ⇒ ข้อมูลต้นทางบกพร่อง
# ไม่ใช่อำเภอใหม่ จึงไม่ต้องเตือนซ้ำทุกครั้งที่รีเฟรช แต่ก็ต้องไม่เขียน "00" ลงคอลัมน์ชื่อ
UNSPECIFIED = "ไม่ระบุอำเภอ"


def amphoe_name(areacode: str) -> str:
    """ชื่ออำเภอจาก areacode — ถ้าไม่รู้จักคืนรหัส 2 หลักเหมือนพฤติกรรมเดิม

    คืนรหัสแทนการคืนค่าว่าง เพราะถ้าต้นทางเพิ่มอำเภอใหม่ ข้อมูลต้องไม่หายไปเฉย ๆ
    ผู้เรียกที่ต้องการรู้ว่ามีรหัสแปลกปลอมให้ใช้ `unknown_codes()`
    """
    a = areacode or ""
    if a[2:4] == "00":
        return UNSPECIFIED
    return AMPHOE.get(a[:4], a[2:4])


def unknown_codes(rows: list[dict]) -> list[str]:
    """รหัส areacode[:4] ที่ยังไม่มีในตาราง — ไว้เตือนว่าตารางนี้ตกยุคแล้ว

    ไม่นับรหัสลงท้าย "00" เพราะเป็นข้อมูลต้นทางที่ไม่ได้ลงรหัสอำเภอ ไม่ใช่อำเภอใหม่
    """
    seen = {(r.get("areacode") or "")[:4] for r in rows}
    return sorted(c for c in seen
                  if len(c) == 4 and c not in AMPHOE and not c.endswith("00"))
