"""Regression tests: ตัดคำตอบที่ LLM "เขียนใหม่ทั้งชุด" (repetition loop)

ล็อกบั๊กจริง: หลังปรับ SYSTEM_PROMPT ให้ตอบยาวขึ้น (ถอดเพดาน 2-3 ประโยค/ประเด็นออก)
Gemini เข้าสู่ repetition loop บ่อยขึ้น — เขียนครบ 4 ส่วนแล้วขึ้นต้น "1. สรุปคำตอบ"
ใหม่อีกรอบ ผู้ใช้เห็นคำตอบเบิ้ล 2 ชุด (วัดจริง: 17,264 ตัวอักษร = 8,577 + 8,687)

กฎเดิมจับไม่ได้เพราะอาศัยหัวข้อ "คำถามติดตาม" เป็นหมุดปิดท้าย แต่ระบบเปลี่ยนไปใช้
บล็อก <<<FOLLOWUPS>>> ซึ่งถูกตัดออกก่อน dedupe ทำงาน
"""
from src.agents.text_utils import dedupe_repeated_answer


def _answer(intro: str) -> str:
    return (
        "**1. สรุปคำตอบ**\n\n"
        f"{intro} " + "เนื้อหาสรุปยาวพอสมควรเพื่อให้ผ่านเกณฑ์ความยาวขั้นต่ำ " * 4 + "\n\n"
        "**2. ข้อมูลจากคลังความรู้**\n\n"
        "| จังหวัด | ตัวชี้วัด | ปี (พ.ศ.) | ค่าที่พบ | เป้าหมาย/เกณฑ์ |\n"
        "|---|---|---|---|---|\n"
        "| ศรีสะเกษ | ความชุกพยาธิใบไม้ตับ | 2566 | 1.59% | ≤ 1% |\n\n"
        "**3. บริบทและการวิเคราะห์**\n\n"
        + "การวิเคราะห์เชิงลึกพร้อมตัวเลขอ้างอิงจากเอกสารจริง " * 4 + "\n\n"
        "**4. ช่องว่างของข้อมูล**\n\n"
        "- ไม่พบข้อมูลปี 2567 ของบางจังหวัด\n"
    )


class TestCutRestartedAnswer:
    def test_เขียนซ้ำทั้งชุดต้องเหลือรอบเดียว(self):
        once = _answer("รอบแรก")
        doubled = once + "\n\n" + _answer("รอบสอง")
        out = dedupe_repeated_answer(doubled)
        assert out.count("**1. สรุปคำตอบ**") == 1
        assert out.count("**4. ช่องว่างของข้อมูล**") == 1
        assert "รอบแรก" in out and "รอบสอง" not in out

    def test_เขียนซ้ำแบบเปลี่ยนคำเล็กน้อยก็ยังต้องตัดได้(self):
        # เคสจริง: สองรอบไม่เหมือนกันเป๊ะ ("ตั้งแต่การคัดกรองประชาชน" vs "ทั้งการคัดกรองประชากร")
        doubled = _answer("ตั้งแต่การคัดกรองประชาชนกลุ่มเสี่ยง") + "\n\n" + _answer("ทั้งการคัดกรองประชากรกลุ่มเสี่ยง")
        out = dedupe_repeated_answer(doubled)
        assert out.count("**2. ข้อมูลจากคลังความรู้**") == 1

    def test_คำตอบปกติต้องไม่ถูกแตะ(self):
        once = _answer("ปกติ")
        assert dedupe_repeated_answer(once) == once

    def test_คำตอบที่มีเลขข้อแต่ไม่ได้เขียนซ้ำต้องไม่ถูกตัด(self):
        text = (
            "**1. สรุปคำตอบ**\n" + "เนื้อหายาวพอที่จะผ่านเกณฑ์ขั้นต่ำของ dedupe " * 6 + "\n"
            "**2. ข้อมูล**\nรายการ\n"
            "**3. วิเคราะห์**\n"
            "ในหัวข้อนี้มีการอ้างถึงลำดับ 1) ปัจจัยแรก 2) ปัจจัยที่สอง ภายในย่อหน้า\n"
        )
        assert dedupe_repeated_answer(text) == text

    def test_คำตอบสั้นไม่ถูกแตะ(self):
        short = "**1. สรุปคำตอบ**\nสั้นมาก"
        assert dedupe_repeated_answer(short) == short
