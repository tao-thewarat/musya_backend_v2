"""Tests: คำถามหางานวิจัยต้องไม่ถูกประวัติแชทเติมชื่อจังหวัดเข้ามา

ที่มา — ผู้ใช้จับได้ 2026-08-03:
  ถาม     "มีงานวิจัยอะไรเรื่องการป้องกันการฆ่าตัวตายในชุมชนชนบท"
  กลายเป็น "...ในชุมชนชนบท **ของจังหวัดยโสธรและจังหวัดศรีสะเกษ** หรือไม่"
  ⇒ ค้น ThaiJo ด้วยชื่อจังหวัดที่ผู้ใช้ไม่ได้ถาม **พบแค่ 3 บทความ**

งานวิจัยวิชาการไม่ผูกกับพื้นที่ — บทความที่ทำในเชียงใหม่ก็ใช้อ้างอิงได้
การใส่ชื่อจังหวัดจึงตัดผลลัพธ์ที่ควรเจอทิ้งเปล่า ๆ

การ์ดเดิม [_narrows_scope] ดักเฉพาะกรณีผู้ใช้ระบุ "เขต 10" ไว้ชัด
เคสนี้ผู้ใช้ **ไม่ได้ระบุขอบเขตอะไรเลย** การ์ดเดิมจึงครอบไม่ถึง
"""
from src.agents.question_resolver import _adds_unasked_place, _narrows_scope
from src.agents.thaijo_agent import _strip_places

Q = "มีงานวิจัยอะไรเรื่องการป้องกันการฆ่าตัวตายในชุมชนชนบท"
BAD = ("มีงานวิจัยเกี่ยวกับการป้องกันการฆ่าตัวตายในชุมชนชนบท"
       "ของจังหวัดยโสธรและจังหวัดศรีสะเกษ หรือไม่")


class TestAddsUnaskedPlace:
    def test_ดักเคสจริงที่ผู้ใช้รายงาน(self):
        assert _adds_unasked_place(Q, BAD) is True

    def test_การ์ดเดิมดักเคสนี้ไม่ได้_จึงต้องมีการ์ดใหม่(self):
        """ยืนยันว่าทำไมต้องเพิ่มการ์ด ไม่ใช่แก้ของเดิม"""
        assert _narrows_scope(Q, BAD) is False

    def test_คำถามอื่นที่หาความรู้ก็ต้องกัน(self):
        for q in ("มีมาตรการอะไรลดอุบัติเหตุจักรยานยนต์บ้าง",
                  "แนวทางการดูแลผู้ป่วยซึมเศร้ามีอะไรบ้าง",
                  "รูปแบบการมีส่วนร่วมของชุมชนที่ได้ผลเป็นอย่างไร"):
            assert _adds_unasked_place(q, q + " ของจังหวัดยโสธร") is True, q

    def test_ถ้าผู้ใช้ถามถึงจังหวัดเองต้องไม่กัน(self):
        q = "มีงานวิจัยเรื่องการฆ่าตัวตายในจังหวัดยโสธรไหม"
        assert _adds_unasked_place(q, q + " ปี 2568") is False

    def test_คำถามตัวเลขยังเติมจังหวัดจากบริบทได้เหมือนเดิม(self):
        """ถาม 'มีผู้ป่วยกี่คน' การเติมจังหวัดจากประวัติยังถูกต้อง — ห้ามแตะ"""
        q = "แล้วปี 2569 มีผู้ป่วยกี่คน"
        assert _adds_unasked_place(q, q + " ของจังหวัดยโสธร") is False

    def test_ไม่เติมพื้นที่ก็ไม่กัน(self):
        assert _adds_unasked_place(Q, Q + " ในช่วงปี 2565-2568") is False


class TestStripPlacesFromSearchTerm:
    def test_ตัดจังหวัดที่ผู้ใช้ไม่ได้ถามออก(self):
        out = _strip_places("ป้องกันการฆ่าตัวตาย ชุมชนชนบท ยโสธร ศรีสะเกษ", Q)
        assert "ยโสธร" not in out and "ศรีสะเกษ" not in out
        assert "ฆ่าตัวตาย" in out and "ชุมชนชนบท" in out

    def test_เก็บจังหวัดไว้ถ้าผู้ใช้ถามเอง(self):
        q = "งานวิจัยการฆ่าตัวตายในยโสธร"
        assert "ยโสธร" in _strip_places("ฆ่าตัวตาย ยโสธร", q)

    def test_ตัดคำว่าจังหวัดที่ค้างอยู่(self):
        out = _strip_places("ฆ่าตัวตาย จังหวัด ยโสธร", Q)
        assert "จังหวัด" not in out and "ยโสธร" not in out

    def test_ถ้าตัดจนเหลือน้อยเกินให้ใช้ของเดิม(self):
        """ค้นด้วยคำว่างยิ่งแย่กว่าค้นด้วยคำที่มีจังหวัดปน"""
        assert _strip_places("ยโสธร", Q) == "ยโสธร"

    def test_ไม่มีจังหวัดก็ไม่เปลี่ยนอะไร(self):
        t = "ป้องกันการฆ่าตัวตาย ชุมชน"
        assert _strip_places(t, Q) == t
